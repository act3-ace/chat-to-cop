"""Evaluate a model against silver labels: compare extractions to reference labels.

Reads silver labels (generated by generate_silver_labels.py), sends the same
messages through a different model, and computes comparison metrics:
- Update type match rate (exact + relaxed)
- Entity overlap (callsign/track number matching)
- Confidence correlation
- Per-type breakdown

Usage:
    # Compare local qwen2.5:7b against silver labels
    python scripts/eval_against_labels.py \\
        --labels data/labels/dash3_silver_labels.jsonl \\
        --url http://127.0.0.1:11434/v1 \\
        --model qwen2.5:7b

    # Compare Groq llama against silver labels
    python scripts/eval_against_labels.py \\
        --labels data/labels/dash3_silver_labels.jsonl \\
        --url https://api.groq.com/openai/v1 \\
        --model llama-3.3-70b-versatile \\
        --api-key $GROQ_API_KEY \\
        --rate-delay 2

Environment:
    GROQ_API_KEY -- API key for Groq
    OPENAI_API_KEY -- Fallback API key source
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import re
import sys
import time
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

from chat_to_cop.backend.openai_compat import (
    DEFAULT_GLOSSARY,
    OpenAICompatibleBackend,
    RetryableError,
    build_system_prompt,
)
from chat_to_cop.models.cop_update import CoPUpdate
from chat_to_cop.models.messages import IRCMessage

# --- Noise filter (same as generate_silver_labels.py) ---
_NOISE_RE = re.compile(
    r"^[\s.]+$"
    r"|^\s*c\s*$"
    r"|^\s*copy\s*$"
    r"|^\s*word\s*$"
    r"|^\s*test\s*$"
    r"|^\s*NSTR\s*$"
    r"|^\s*roger\s*$"
    r"|^\s*affirm\s*$"
    r"|^\s*wilco\s*$",
    re.IGNORECASE,
)
_URL_RE = re.compile(r"https?://\S+")
_RADIO_CHECK_RE = re.compile(r"radio\s+check", re.IGNORECASE)
_EXERCISE_CONTROL_RE = re.compile(
    r"\*{3,}.*(?:STARTEX|ENDEX|START\s+EX|END\s+EX).*\*{3,}"
    r"|^\s*(?:STARTEX|ENDEX)\b",
    re.IGNORECASE,
)


def _is_noise(content: str) -> bool:
    """Check if a message is noise that shouldn't be sent to the LLM."""
    stripped = content.strip()
    if not stripped or len(stripped) <= 1:
        return True
    if _NOISE_RE.match(stripped):
        return True
    if _URL_RE.match(stripped):
        return True
    if _RADIO_CHECK_RE.search(stripped):
        return True
    if _EXERCISE_CONTROL_RE.search(stripped):
        return True
    return False


# Update types that are considered equivalent for relaxed matching
_RELAXED_EQUIVALENTS = [
    {"status_change", "sitrep"},
]


def _types_match_relaxed(a: str, b: str) -> bool:
    """Check if two update types match, allowing related types."""
    if a == b:
        return True
    for group in _RELAXED_EQUIVALENTS:
        if a in group and b in group:
            return True
    return False


def _normalize_key(s: str) -> str:
    """Normalize a callsign or track number for matching."""
    return s.strip().upper().replace(" ", "").replace("-", "").replace("_", "")


def _entity_keys(entities: list[dict]) -> set[str]:
    """Extract normalized matching keys from entity dicts."""
    keys = set()
    for ent in entities:
        tn = ent.get("track_number")
        cs = ent.get("callsign")
        if tn:
            keys.add(_normalize_key(tn))
        if cs:
            keys.add(_normalize_key(cs))
    return keys


def _build_single_message_prompt(msg: IRCMessage) -> list[dict[str, str]]:
    """Build a prompt for a single message (no conversation window)."""
    system_prompt = build_system_prompt(glossary=DEFAULT_GLOSSARY)
    user_content = (
        f"EXTRACT FROM THIS MESSAGE ONLY:\n[{msg.timestamp.strftime('%H:%M:%S')}] {msg.sender}: {msg.content}"
    )
    return [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_content},
    ]


def load_labels(path: str) -> list[dict]:
    """Load silver labels from JSONL file."""
    labels = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                labels.append(json.loads(line))
            except json.JSONDecodeError:
                continue
    return labels


def label_to_irc_message(label: dict) -> IRCMessage:
    """Reconstruct an IRCMessage from a label dict."""
    ts = label.get("timestamp", "2025-09-23T00:00:00+00:00")
    if isinstance(ts, str):
        try:
            timestamp = datetime.fromisoformat(ts)
        except ValueError:
            timestamp = datetime(2025, 9, 23, tzinfo=timezone.utc)
    else:
        timestamp = datetime(2025, 9, 23, tzinfo=timezone.utc)

    return IRCMessage(
        timestamp=timestamp,
        channel=label.get("channel", "#unknown"),
        sender=label.get("sender", "unknown"),
        content=_extract_content_from_raw(label.get("raw_line", "")),
        raw_line=label.get("raw_line", ""),
    )


def _extract_content_from_raw(raw_line: str) -> str:
    """Extract the message content from a raw log line."""
    # Try combined format: [HH:MM:SS] #channel sender: message
    m = re.match(r"^\[[\d:]+\]\s+#\S+\s+\S+?:\s*(.*)", raw_line)
    if m:
        return m.group(1)
    # Try per-channel format: [HH:MM:SS] sender: message
    m = re.match(r"^\[[\d:]+\]\s+\S+?:\s*(.*)", raw_line)
    if m:
        return m.group(1)
    return raw_line


async def eval_against_labels(
    labels: list[dict],
    url: str,
    model: str,
    api_key: str,
    count: int | None,
    rate_delay: float,
    verbose: bool,
) -> dict:
    """Run evaluation and return metrics dict."""
    if count is not None:
        labels = labels[:count]

    # Filter out error labels from the silver set
    labels = [lb for lb in labels if lb.get("extraction_method") != "error"]

    backend = OpenAICompatibleBackend(
        base_url=url,
        model=model,
        api_key=api_key,
        timeout=120.0,
        max_retries=3,
    )

    # Metrics
    total = len(labels)
    type_exact_match = 0
    type_relaxed_match = 0
    entity_overlap_sum = 0.0
    entity_overlap_count = 0
    confidence_pairs: list[tuple[float, float]] = []  # (silver, candidate)
    per_type_correct: Counter[str] = Counter()
    per_type_total: Counter[str] = Counter()
    latencies: list[float] = []
    errors = 0
    noise_skipped = 0
    last_llm_call = 0.0

    print(f"\n{'=' * 70}")
    print(f"EVALUATING: {model} @ {url}")
    print(f"Against {total} silver labels")
    if rate_delay > 0:
        non_noise = sum(1 for lb in labels if lb.get("extraction_method") != "noise_filter")
        est_min = non_noise * rate_delay / 60
        print(f"Rate delay: {rate_delay:.1f}s (~{est_min:.0f} min for {non_noise} LLM calls)")
    print(f"{'=' * 70}\n")

    for i, label in enumerate(labels):
        silver_type = label.get("extracted_type", "none")
        silver_entities = label.get("extracted_entities", [])
        silver_confidence = label.get("confidence", 0.0)

        msg = label_to_irc_message(label)

        # If the silver label was noise-filtered, just check if our filter agrees
        if label.get("extraction_method") == "noise_filter":
            if _is_noise(msg.content):
                type_exact_match += 1
                type_relaxed_match += 1
                per_type_correct["none"] += 1
            per_type_total["none"] += 1
            noise_skipped += 1
            _print_progress(i + 1, total, type_exact_match, errors, noise_skipped)
            continue

        # Skip noise on candidate side too (saves API calls for acks)
        if _is_noise(msg.content):
            # Silver label had content but we're filtering it
            candidate_type = "none"
            candidate_entities: list[dict] = []
            candidate_confidence = 0.0
        else:
            # Rate limiting
            if rate_delay > 0 and last_llm_call > 0:
                elapsed = time.perf_counter() - last_llm_call
                if elapsed < rate_delay:
                    await asyncio.sleep(rate_delay - elapsed)

            # Extract via LLM
            prompt = _build_single_message_prompt(msg)
            retries = 0
            max_retries = 5
            result = None

            while True:
                try:
                    start = time.perf_counter()
                    result = await backend.extract(prompt, CoPUpdate)
                    elapsed = time.perf_counter() - start
                    last_llm_call = time.perf_counter()
                    latencies.append(elapsed)
                    break
                except RetryableError:
                    retries += 1
                    if retries > max_retries:
                        errors += 1
                        break
                    backoff = 5 * (2 ** (retries - 1))
                    print(f"\n  Rate limited (attempt {retries}/{max_retries}), backing off {backoff}s...")
                    await asyncio.sleep(backoff)
                except Exception:
                    errors += 1
                    break

            if result is None:
                _print_progress(i + 1, total, type_exact_match, errors, noise_skipped)
                continue

            candidate_type = result.update_type.value
            candidate_entities = [ent.model_dump(exclude_none=True, exclude_defaults=True) for ent in result.entities]
            candidate_confidence = result.confidence

        # Score: update type
        per_type_total[silver_type] += 1
        if candidate_type == silver_type:
            type_exact_match += 1
            type_relaxed_match += 1
            per_type_correct[silver_type] += 1
        elif _types_match_relaxed(candidate_type, silver_type):
            type_relaxed_match += 1
            per_type_correct[silver_type] += 1

        # Score: entity overlap (Jaccard)
        silver_keys = _entity_keys(silver_entities)
        candidate_keys = _entity_keys(candidate_entities)
        if silver_keys or candidate_keys:
            union = silver_keys | candidate_keys
            intersection = silver_keys & candidate_keys
            overlap = len(intersection) / len(union) if union else 1.0
            entity_overlap_sum += overlap
            entity_overlap_count += 1

        # Confidence correlation
        confidence_pairs.append((silver_confidence, candidate_confidence))

        if verbose:
            if candidate_type == silver_type:
                match_str = "=="
            elif _types_match_relaxed(candidate_type, silver_type):
                match_str = "~="
            else:
                match_str = "!="
            ent_str = ""
            if silver_keys or candidate_keys:
                intersection = silver_keys & candidate_keys
                ent_str = f" ent={len(intersection)}/{len(silver_keys | candidate_keys)}"
            print(
                f"\n  [{i + 1:>4d}] {match_str} silver={silver_type:15s} got={candidate_type:15s}"
                f" conf={silver_confidence:.2f}->{candidate_confidence:.2f}{ent_str}"
                f" | {msg.content[:60]}"
            )

        _print_progress(i + 1, total, type_exact_match, errors, noise_skipped)

    # Compute summary metrics
    scorable = total - noise_skipped
    exact_rate = type_exact_match / total if total > 0 else 0
    relaxed_rate = type_relaxed_match / total if total > 0 else 0
    entity_overlap_avg = entity_overlap_sum / entity_overlap_count if entity_overlap_count > 0 else 0
    conf_corr = _pearson_correlation(confidence_pairs) if len(confidence_pairs) > 2 else 0.0

    metrics = {
        "model": model,
        "silver_labels": total,
        "scorable": scorable,
        "noise_skipped": noise_skipped,
        "errors": errors,
        "type_exact_match_rate": exact_rate,
        "type_relaxed_match_rate": relaxed_rate,
        "entity_overlap_avg": entity_overlap_avg,
        "confidence_correlation": conf_corr,
        "per_type_correct": dict(per_type_correct),
        "per_type_total": dict(per_type_total),
    }
    if latencies:
        sorted_lat = sorted(latencies)
        metrics["p50_latency"] = sorted_lat[len(sorted_lat) // 2]
        metrics["p95_latency"] = sorted_lat[int(len(sorted_lat) * 0.95)]

    # Print summary
    print(f"\n\n{'=' * 70}")
    print(f"RESULTS: {model}")
    print(f"{'=' * 70}")
    print(f"  Silver labels:          {total}")
    print(f"  Scorable (non-noise):   {scorable}")
    print(f"  Errors:                 {errors}")
    print()
    print(f"  Type match (exact):     {exact_rate:.1%}")
    print(f"  Type match (relaxed):   {relaxed_rate:.1%}")
    print(f"  Entity overlap (avg):   {entity_overlap_avg:.1%}")
    print(f"  Confidence correlation: {conf_corr:.3f}")
    if latencies:
        print(f"  Latency p50:            {metrics['p50_latency']:.2f}s")
        print(f"  Latency p95:            {metrics['p95_latency']:.2f}s")

    # Per-type breakdown
    if per_type_total:
        print(f"\n  {'Type':25s} {'Correct':>8s} {'Total':>8s} {'Rate':>8s}")
        print(f"  {'-' * 51}")
        for utype in sorted(per_type_total.keys()):
            correct = per_type_correct[utype]
            tot = per_type_total[utype]
            rate = correct / tot if tot > 0 else 0
            print(f"  {utype:25s} {correct:>8d} {tot:>8d} {rate:>7.0%}")

    return metrics


def _pearson_correlation(pairs: list[tuple[float, float]]) -> float:
    """Compute Pearson correlation between two series."""
    n = len(pairs)
    if n < 3:
        return 0.0
    xs = [p[0] for p in pairs]
    ys = [p[1] for p in pairs]
    mean_x = sum(xs) / n
    mean_y = sum(ys) / n
    cov = sum((x - mean_x) * (y - mean_y) for x, y in zip(xs, ys))
    var_x = sum((x - mean_x) ** 2 for x in xs)
    var_y = sum((y - mean_y) ** 2 for y in ys)
    denom = (var_x * var_y) ** 0.5
    if denom == 0:
        return 0.0
    return cov / denom


def _print_progress(current: int, total: int, correct: int, errors: int, noise: int) -> None:
    """Print a single-line progress update."""
    pct = current / total * 100 if total > 0 else 0
    rate = correct / current * 100 if current > 0 else 0
    print(
        f"\r  [{current:>5d}/{total}] {pct:5.1f}%  match={rate:.1f}%  errors={errors} noise={noise}    ",
        end="",
        flush=True,
    )


def main():
    parser = argparse.ArgumentParser(
        description="Evaluate a model against silver labels",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
    # Compare local model against silver labels
    python scripts/eval_against_labels.py \\
        --labels data/labels/dash3_silver_labels.jsonl \\
        --url http://127.0.0.1:11434/v1 \\
        --model qwen2.5:7b

    # Compare Groq model
    python scripts/eval_against_labels.py \\
        --labels data/labels/dash3_silver_labels.jsonl \\
        --url https://api.groq.com/openai/v1 \\
        --model llama-3.3-70b-versatile \\
        --api-key $GROQ_API_KEY \\
        --rate-delay 2
        """,
    )
    parser.add_argument(
        "--labels",
        default="data/labels/dash3_silver_labels.jsonl",
        help="Path to silver labels JSONL. Default: data/labels/dash3_silver_labels.jsonl",
    )
    parser.add_argument(
        "--url",
        default="http://127.0.0.1:11434/v1",
        help="OpenAI-compatible API base URL. Default: local Ollama",
    )
    parser.add_argument(
        "--model",
        default="qwen2.5:7b",
        help="Model to evaluate. Default: qwen2.5:7b",
    )
    parser.add_argument(
        "--api-key",
        default=None,
        help="API key (or set GROQ_API_KEY / OPENAI_API_KEY env var)",
    )
    parser.add_argument(
        "--count",
        type=int,
        default=None,
        help="Limit to first N labels. Default: all",
    )
    parser.add_argument(
        "--rate-delay",
        type=float,
        default=0.0,
        help="Seconds between LLM calls. Default: 0 (local). Use 2 for Groq free tier.",
    )
    parser.add_argument(
        "--verbose",
        "-v",
        action="store_true",
        help="Show per-message comparison results",
    )
    args = parser.parse_args()

    # Resolve API key
    api_key = args.api_key or os.environ.get("GROQ_API_KEY") or os.environ.get("OPENAI_API_KEY", "not-needed")

    # Load labels
    labels_path = Path(args.labels)
    if not labels_path.exists():
        print(f"ERROR: Labels file not found: {labels_path}")
        print("Run generate_silver_labels.py first to create the reference labels.")
        sys.exit(1)

    labels = load_labels(str(labels_path))
    if not labels:
        print(f"ERROR: No labels found in {labels_path}")
        sys.exit(1)
    print(f"Loaded {len(labels)} silver labels from {labels_path}")

    asyncio.run(
        eval_against_labels(
            labels=labels,
            url=args.url,
            model=args.model,
            api_key=api_key,
            count=args.count,
            rate_delay=args.rate_delay,
            verbose=args.verbose,
        )
    )


if __name__ == "__main__":
    main()
